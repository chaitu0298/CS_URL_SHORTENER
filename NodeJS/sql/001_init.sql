-- Safe to re-run; additive migrations must be versioned separately going forward.
CREATE TABLE IF NOT EXISTS short_links (
 code VARCHAR(32) PRIMARY KEY,
 owner_sub VARCHAR(128) NOT NULL,
 destination VARCHAR(2048) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 expires_at TIMESTAMPTZ NOT NULL,
 revoked_at TIMESTAMPTZ,
 click_count BIGINT NOT NULL DEFAULT 0 CHECK (click_count >= 0)
);
CREATE INDEX IF NOT EXISTS idx_short_links_expiry ON short_links(expires_at);
CREATE TABLE IF NOT EXISTS idempotency_requests (
 request_key VARCHAR(128) NOT NULL,
 owner_sub VARCHAR(128) NOT NULL,
 fingerprint CHAR(64) NOT NULL,
 code VARCHAR(32) NOT NULL REFERENCES short_links(code) ON DELETE CASCADE,
 PRIMARY KEY(owner_sub,request_key)
);
CREATE TABLE IF NOT EXISTS click_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(32) NOT NULL REFERENCES short_links(code) ON DELETE CASCADE,
 happened_at TIMESTAMPTZ NOT NULL,
 day_utc VARCHAR(10) NOT NULL,
 visitor_hash VARCHAR(20)
);
CREATE INDEX IF NOT EXISTS idx_click_events_code_day ON click_events(code,day_utc);
CREATE INDEX IF NOT EXISTS idx_click_events_expiry ON click_events(happened_at);
